-- Matches the reviewed local delivery table. Existing tables/data are not replaced.
CREATE TABLE IF NOT EXISTS message_deliveries (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  workspace_key VARCHAR(100) NOT NULL,
  wamid VARCHAR(255) NULL,
  contact_id BIGINT UNSIGNED NULL,
  recipient_phone VARCHAR(32) NOT NULL,
  campaign_name VARCHAR(255) NOT NULL DEFAULT '',
  template_name VARCHAR(512) NOT NULL DEFAULT '',
  status VARCHAR(32) NOT NULL,
  error_code VARCHAR(64) NULL,
  error_message TEXT NULL,
  unit_price DECIMAL(10,4) NOT NULL DEFAULT 0,
  charged_amount DECIMAL(10,4) NOT NULL DEFAULT 0,
  credit_due DECIMAL(10,4) NOT NULL DEFAULT 0,
  status_payload JSON NULL,
  accepted_at TIMESTAMP NULL DEFAULT NULL,
  sent_at TIMESTAMP NULL DEFAULT NULL,
  delivered_at TIMESTAMP NULL DEFAULT NULL,
  read_at TIMESTAMP NULL DEFAULT NULL,
  failed_at TIMESTAMP NULL DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_message_deliveries_wamid (workspace_key, wamid),
  KEY idx_message_deliveries_contact (workspace_key, contact_id),
  KEY idx_message_deliveries_created (workspace_key, created_at),
  KEY idx_message_deliveries_recipient (workspace_key, recipient_phone),
  KEY idx_message_deliveries_status (workspace_key, status),
  KEY idx_message_deliveries_status_created (workspace_key, status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
